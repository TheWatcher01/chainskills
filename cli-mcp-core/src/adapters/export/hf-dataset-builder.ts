function inferProvider(model: string): string {
    const lower = model.toLowerCase();
    if (lower.includes('claude')) return 'anthropic';
    if (lower.includes('gpt') || lower.includes('o3')) return 'openai';
    return 'ollama';
}

function extractDomain(workflow: string): string {
    // Try common patterns
    const parts = workflow.split('/');
    if (parts.length >= 2) return parts[0] ?? 'unknown';
    return 'unknown';
}

function extractDifficulty(workflow: string): string {
    const parts = workflow.split('/');
    if (parts.length >= 3) return parts[1] ?? 'unknown';
    return 'unknown';
}
